"""Write scaling_tables.tex from the committed scaling_data.json (ledger ids in comments).
Run: python3 code/make_scaling_tables.py   (from docs/manuscript)"""
import json, pathlib
here = pathlib.Path(__file__).parent
d = json.loads((here / "scaling_data.json").read_text())
name = lambda m: "\\texttt{" + m.replace("-", "{-}").replace("_", "\\_") + "}"
order = ["xag", "xag-bennett", "sb-simple", "sb-balanced", "sb-minimal", "structure-sequential"]
def num(x): return ("%g" % x).replace("-", "$-$")
L = ["% generated by code/make_scaling_tables.py from code/scaling_data.json; do not edit by hand"]
L.append("% T8-3, T8-4")
L.append("\\begin{table}\n\\centering\n\\caption{Oracle $T$ count on 36 random graphs ($n=4$--10 vertices, $m$ edges, $k=3$, three graph seeds each, $n+m\\le 32$): least-squares fit $T=a+bn+cm$. $R^2=1$ rows are exact; the three seeds give identical $T$ for every method.}")
L.append("\\label{tab:fits}\n\\small\n\\begin{tabular}{lrrrr}\n\\toprule\nmethod & $a$ & $b$ (per vertex) & $c$ (per edge) & $R^2$ \\\\\n\\midrule")
for m in order:
    f = d["fits"][m]
    L.append(f"{name(m)} & {num(f['a'])} & {num(f['b'])} & {num(f['c'])} & {f['R2']:.4f} \\\\")
L.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
L.append("% T8-7, T8-8, T8-9 (P12, C12 from task-35 rows.json: [T, T depth, qubits])")
L.append("\\begin{table}\n\\centering\n\\caption{Path $P_{12}$ and cycle $C_{12}$, $k=3$, regime R1, one iteration: oracle $T$ count / $T$ depth / qubits after multi-controlled expansion.}")
L.append("\\label{tab:p12}\n\\small\n\\begin{tabular}{lcc}\n\\toprule\nmethod & $P_{12}$ & $C_{12}$ \\\\\n\\midrule")
for m in order:
    cells = []
    for g in ("P12", "C12"):
        t, dp, q = d["pc"][g][m]
        cells.append(f"{t} / {int(dp)} / {q}")
    L.append(f"{name(m)} & " + " & ".join(cells) + " \\\\")
L.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
L.append("% T5-1, T5-2, T5-3")
for g, cap in (("K4", "$K_4$ (four colors)"), ("C5", "$C_5$ (three colors)")):
    prof = d["profiles"][g]
    L.append(f"\\begin{{table}}\n\\centering\n\\caption{{Optimization profile, {cap}, regime R1, seed 7: oracle $T$ count / $T$ depth. Qubit counts change only for \\texttt{{refactoring}} on $C_5$ (see text).}}")
    L.append(f"\\label{{tab:prof-{g}}}\n\\small\n\\begin{{tabular}}{{lcccc}}\n\\toprule\nmethod & none & refactoring & balanced & cut\\_esop\\_balancing \\\\\n\\midrule")
    for m in sorted(prof):
        L.append(f"{name(m)} & " + " & ".join(f"{c[0]} / {c[1]}" for c in prof[m]) + " \\\\")
    L.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
(here.parent / "scaling_tables.tex").write_text("\n".join(L) + "\n")
