"""Write results_tables.tex from the committed results_data.json (ledger ids in comments).
Run: python3 code/make_results_tables.py   (from docs/manuscript)"""
import json, pathlib
here = pathlib.Path(__file__).parent
d = json.loads((here / "results_data.json").read_text())
norm = lambda m: m.replace("_", "-")
tx = lambda m: m.replace("-", "\\text{-}")
def name(m): return "\\texttt{" + m.replace("-", "{-}") + "}"
graphs = ["K3", "K4", "C5"]
methods = sorted({m for g in graphs for m in d["oracle_T"][g]})
L = []
L.append("% generated by code/make_results_tables.py from code/results_data.json; do not edit by hand")
L.append("% ledger ids: oracle T = P6 (K3), P10 (K4, C5); T depth same rows")
L.append("\\begin{table}\n\\centering\n\\caption{Oracle-only Clifford+$T$ cost, regime R1, seed 7, \\texttt{n\\_clean\\_m15} multi-controlled expansion: $T$ count / $T$ depth. A dash marks a method excluded from a graph (see text).}")
L.append("\\label{tab:oracle-t}\n\\small\n\\begin{tabular}{lccc}\n\\toprule\nmethod & K3 & K4 & C5 \\\\\n\\midrule")
for m in methods:
    cells = []
    for g in graphs:
        v = d["oracle_T"][g].get(m)
        cells.append(f"{v[0]} / {v[1]}" if v else "--")
    L.append(f"{name(m)} & " + " & ".join(cells) + " \\\\")
L.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
L.append("% P11 (search T), P14 (offset D)")
L.append("\\begin{table}\n\\centering\n\\caption{One Grover iteration ($j=1$), regime R1: $T$ count of preparation, oracle and diffusion. The search count equals the oracle count plus a method-independent offset $D$.}")
L.append("\\label{tab:search-t}\n\\small\n\\begin{tabular}{lcc}\n\\toprule\nmethod & K4 ($D=%d$) & C5 ($D=%d$) \\\\\n\\midrule" % (d["offset_D"]["K4"], d["offset_D"]["C5"]))
for m in sorted(d["search_T"]["K4"]):
    L.append(f"{name(m)} & {d['search_T']['K4'][m]} & {d['search_T']['C5'][m]} \\\\")
L.append("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
L.append("% T4-2")
L.append("\\begin{table}\n\\centering\n\\caption{K3, regime R1: oracle logical qubits / gates / depth (mixed gate granularity, not $T$-costed).}")
L.append("\\label{tab:k3-qgd}\n\\small\n\\begin{tabular}{lccc}\n\\toprule\nmethod & qubits & gates & depth \\\\\n\\midrule")
for m in sorted(d["k3_qgd"], key=norm):
    q, g, dp = d["k3_qgd"][m]
    L.append(f"{name(norm(m))} & {q} & {g} & {dp} \\\\")
L.append("\\bottomrule\n\\end{tabular}\n\\end{table}")
(here.parent / "results_tables.tex").write_text("\n".join(L) + "\n")
